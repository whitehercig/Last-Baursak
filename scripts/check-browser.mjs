import { chromium } from 'playwright';
import fs from 'node:fs';
const browser=await chromium.launch({headless:true,channel:"chrome"});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5187/',{waitUntil:'networkidle'});
await page.screenshot({path:'docs/screenshots/desktop.png',fullPage:true});
await page.getByRole('button',{name:'Начать забег'}).click();
await page.waitForTimeout(2200);
await page.keyboard.down('ArrowUp');await page.waitForTimeout(1400);await page.keyboard.up('ArrowUp');
await page.screenshot({path:'docs/screenshots/gameplay.png',fullPage:true});
const status=await page.locator('[data-game-status]').getAttribute('data-game-status');
await page.getByRole('button',{name:'Пауза',exact:true}).click();await page.getByRole('button',{name:'Продолжить',exact:false}).click();
await page.getByRole('button',{name:'Выйти из забега'}).click();await page.getByRole('button',{name:'Эстафета',exact:false}).click();
await page.getByRole('button',{name:'Подключить кошелёк',exact:false}).last().click();await page.getByRole('alert').waitFor();
const desktopOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1});mobile.on('pageerror',e=>errors.push(e.message));
await mobile.goto('http://127.0.0.1:5187/',{waitUntil:'networkidle'});await mobile.screenshot({path:'docs/screenshots/mobile.png',fullPage:true});
const mobileOverflow=await mobile.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
await mobile.getByRole('button',{name:'Начать забег'}).click();await mobile.waitForTimeout(2100);
await mobile.screenshot({path:'docs/screenshots/mobile-game.png',fullPage:true});
console.log(JSON.stringify({errors,status,desktopOverflow,mobileOverflow,touchControls:await mobile.getByRole('button',{name:'Джойстик движения'}).isVisible()}));
await browser.close();
